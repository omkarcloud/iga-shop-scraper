"""Cache TTL per /iga-shop/* endpoint (cache.py, keyed on the validated
params). IGA's specials and prices roll over on Wednesdays and stock moves
through the day, so listings and products stay short; the store list, the
category tree and the sitemaps change on the scale of weeks.
"""
from datetime import timedelta

# The full store list (540 rows, one upstream call) behind stores/details
# and every `store` resolution: stores open or close monthly at most.
STORE_LIST_CACHE = timedelta(hours=24)
# stores/search and stores/nearby: same data, the site's own ordering.
STORES_CACHE = timedelta(hours=12)
# Product search / specials / category listings: prices and availability
# per store; one hour keeps a hot query cheap without serving last week's
# special past its Wednesday rollover for long.
LISTING_CACHE = timedelta(hours=1)
# One product at one store: same cadence as the listings.
PRODUCT_CACHE = timedelta(hours=1)
# The category tree per store (one upstream call; categories/list and every
# `category` resolution read it): the range tree changes rarely.
CATEGORY_TREE_CACHE = timedelta(hours=24)
# The subcategory preview is a listing in disguise.
CATEGORY_OVERVIEW_CACHE = timedelta(hours=1)
# Recipes are editorial content with linked products; the product prices
# inside a recipe move hourly but the recipe itself is stable.
RECIPES_CACHE = timedelta(hours=6)
# The raw sitemaps (1.4 MB for products): regenerated by the site daily.
SITEMAP_CACHE = timedelta(hours=24)
